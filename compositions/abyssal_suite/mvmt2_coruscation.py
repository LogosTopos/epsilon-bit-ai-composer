def near_chord(p, chord):
    pc = p % 12
    if pc in CHORD_PC[chord]:
        return p
    for d in (1, 2):
        for cand in (p - d, p + d):
            if cand % 12 in CHORD_PC[chord]:
                return cand
    return p


def counter6(p, chord):
    """下方六度对位(承袭:非和弦音就近归位)"""
    return near_chord(p - 9, chord)


