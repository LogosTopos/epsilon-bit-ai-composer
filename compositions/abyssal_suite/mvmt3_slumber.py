    s.prog('vla', *PROGS['vla_slow'][:2], B(49))
    s.prog('celli', *PROGS['celli_slow'][:2], B(49))
    s.prog('oboe', *PROGS['eng_horn'][:2], B(61))
    for t, p, d in T(THEME_D, -7):                    # 大提琴:主题于 g 小调
        s.note('celli', p, 84, B(49) + t, d)
    for t, p, d in T(THEME_D, -7):                    # 中提琴:相隔两小节卡农
        s.note('vla', p, 80, B(51) + t, d)
    for t, p, d in DESCANT:
        s.note('vln1', p, 76, B(49) + t, d)
    for n in range(49, 65):
        ch = H[n]
        s.chord('vln2', (CHT[ch][0] + 12, CHT[ch][1] + 12, CHT[ch][2] + 12), 42, B(n), 4.0)
        s.note('bass', ROOT[ch], 48, B(n), 4.0)
    for t, p, d in EH_ECHO:
        s.note('eng_horn', p, 64, B(61) + t, d)
    for bn, v in [(49, 56), (53, 60), (57, 62), (61, 64), (63, 60)]:
        dyn('celli', v, bn); dyn('vla', v - 4, bn); dyn('vln1', v - 6, bn)
    dyn('vln2', 44, 49); dyn('eng_horn', 50, 61)

    # ---------------- 变奏 3(m65-80):铜管圣咏 + 全奏 ----------------
    s.prog('vla', *PROGS['vla_slow'][:2], B(65))
    s.prog('horn', *PROGS['brass_sec'][:2], B(65))    # 圆号 → 铜管组(无声区)
    for t, p, d in THEME_D:
        s.note('vln1', p + 12, 96, B(65) + t, d)
        s.note('trumpet', p + 12, 88, B(65) + t, d)
    for n in range(65, 81):
        s.chord('choir', CHOIR[H[n]], 60, B(n), 4.0)
        ch = H[n]
        s.chord('brass_sec', BRASS[ch], 74, B(n), 4.0)          # 铜管圣咏柱式
        s.chord('vln2', (CHT[ch][0] + 12, CHT[ch][1] + 12, CHT[ch][2] + 12), 52, B(n), 4.0)
        if n >= 67:
            s.chord('vla', (CHT[ch][0], CHT[ch][1]), 48, B(n), 4.0)
        s.note('celli', ROOT8[ch], 60, B(n), 4.0)
        s.note('bass', ROOT[ch], 58, B(n), 4.0)
        s.note('organ', ROOT8[ch], 48, B(n), 4.0)
    # 定音鼓滚奏与重音
    s.roll('timpani', 46, 30, 72, B(65), B(69), step=0.25)
    s.roll('timpani', 46, 40, 80, B(73), B(77), step=0.25)
    s.roll('timpani', 41, 45, 85, B(79), B(81), step=0.25)
    for n in (69, 77):
        s.note('timpani', 46, 74, B(n), 0.8)
        s.note('drums', 36, 78, B(n), 0.5)
    s.note('drums', 49, 92, B(80) + 2, 2.0)
    s.note('timpani', 46, 80, B(80) + 3, 1.0)
    for bn, v in [(65, 62), (69, 70), (73, 78), (77, 84), (79, 88), (80, 78)]:
        dyn('vln1', v, bn); dyn('trumpet', v - 8, bn); dyn('choir', v - 14, bn)
        dyn('brass_sec', v - 12, bn); dyn('vln2', v - 18, bn); dyn('vla', v - 20, bn)
        dyn('celli', v - 14, bn); dyn('bass', v - 16, bn); dyn('organ', v - 22, bn)

    # ---------------- 尾声(m81-88):长笛 + 钢片琴,归于寂静 ----------------
    s.prog('organ', *PROGS['celesta'][:2], B(81))     # 管风琴 → 钢片琴
    for n in range(81, 89):
        s.note('bass', 34, 38, B(n), 4.0)
        s.note('vln2', 62, 34, B(n), 4.0)
        s.note('vla', 58, 34, B(n), 4.0)
    for t, p, d in [(B(81), 70, 2.0), (B(81) + 2, 69, 1.0), (B(81) + 3, 65, 1.0),
                    (B(83), 67, 2.0), (B(83) + 2, 69, 1.0), (B(83) + 3, 70, 1.0),
                    (B(85), 72, 2.0), (B(85) + 2, 70, 1.0), (B(85) + 3, 69, 1.0),
                    (B(87), 70, 2.0), (B(87) + 2, 69, 1.0), (B(87) + 3, 65, 2.0)]:
        s.note('flute', p, 54, t, d)
    for t, p in [(B(81), 82), (B(81) + 2, 86), (B(83) + 2, 84), (B(85) + 2, 86),
                 (B(87) + 2, 82), (B(87) + 4, 84)]:
        s.note('celesta', p, 44, t, 2.0)
    for bn, v in [(81, 38), (83, 34), (85, 30), (87, 26)]:
        dyn('flute', v, bn)
    dyn('bass', 26, 81); dyn('vln2', 26, 81); dyn('vla', 24, 81)


