def fig(p, d):
    """十六分减缩:旋律音 → (p, p+2, p+3, p+2) 音型(全在 Bb 大调内)"""
    out = []
    n = int(round(d * 4))
    pat = (0, 2, 3, 2)
    for i in range(n):
        out.append((i * 0.25, p + pat[i % 4], 0.18))
    return out


def build(s: Score):
    regs = [
        ('piano', CH['piano'], *PROGS['piano']),
        ('harp', CH['harp'], *PROGS['harp']),
        ('vln1', CH['vln1'], *PROGS['vln1_slow']),
        ('vln2', CH['vln2'], *PROGS['vln2_slow']),
        ('vla', CH['vla'], *PROGS['vla_slow']),
        ('celli', CH['celli'], *PROGS['celli_slow']),
        ('bass', CH['bass'], *PROGS['bass_slow']),
        ('flute', CH['flute'], *PROGS['flute']),
        ('oboe', CH['oboe'], *PROGS['oboe']),
        ('eng_horn', CH['oboe'], *PROGS['eng_horn']),
        ('drums', CH['drums'], 128, 0, (0, 127)),
        ('timpani', CH['timpani'], *PROGS['timpani']),
        ('horn', CH['horns'], *PROGS['horn']),
        ('brass_sec', CH['horns'], *PROGS['brass_sec']),
        ('trumpet', CH['brass'], *PROGS['trumpet']),
        ('choir', CH['choir'], *PROGS['choir']),
        ('organ', CH['keys'], *PROGS['organ']),
        ('celesta', CH['keys'], *PROGS['celesta']),
    ]
    for name, ch, bank, prog, (lo, hi) in regs:
        s.add_instr(name, ch, bank, prog, lo, hi)
        s.cc(name, 7, 100, 0.0)
    s.cc('timpani', 7, 88, 0.0)

    def dyn(inst, v, bar_n):
        s.cc(inst, 11, v, B(bar_n))

    s.tempo(76, B(1))

    # ---------------- 主题 D(m1-16):弦乐四部合唱 ----------------
    for n in range(1, 17):
        ch = H[n]
        s.note('vln2', ALTO[n], 50, B(n), 4.0)
        s.note('vla', TENOR[n], 50, B(n), 4.0)
        r1, r2 = CELLO_BASS[n]
        s.note('celli', r1, 56, B(n), 2.0)
        s.note('celli', r2, 54, B(n) + 2, 2.0)
        s.note('bass', ROOT[ch], 52, B(n), 4.0)
    for t, p, d in THEME_D:
        s.note('vln1', p, 92, B(1) + t, d)
    for bn, v in [(1, 56), (5, 60), (9, 62), (13, 64), (16, 58)]:
        dyn('vln1', v, bn); dyn('vln2', v - 6, bn); dyn('vla', v - 6, bn)
        dyn('celli', v - 4, bn); dyn('bass', v - 6, bn)

    # ---------------- 主题反复(m17-32):合唱 + 圆号对位 + 竖琴 ----------------
    for t, p, d in THEME_D:
        s.note('vln1', p, 92, B(17) + t, d)
    for n in range(17, 33):
        s.chord('choir', CHOIR[H[n]], 54, B(n), 4.0)
    for t, p, d in HORN_DESC:
        s.note('horn', p, 72, B(17) + t, d)
    for n in range(17, 33):
        ch = H[n]
        s.note('vln2', ALTO[n - 16], 48, B(n), 4.0)
        s.note('vla', TENOR[n - 16], 48, B(n), 4.0)
        r1, r2 = CELLO_BASS[n - 16]
        s.note('celli', r1, 52, B(n), 2.0)
        s.note('celli', r2, 50, B(n) + 2, 2.0)
        s.note('bass', ROOT[ch], 48, B(n), 4.0)
        s.arp('harp', HARP[ch], 52, B(n), 0.5, 1, 2.0)
    for bn, v in [(17, 56), (21, 60), (25, 62), (29, 64), (31, 58)]:
        dyn('vln1', v, bn); dyn('choir', v - 4, bn); dyn('horn', v - 6, bn)

    # ---------------- 变奏 1(m33-48):长笛十六分减缩 + 双簧管应答 + 钢琴 ----------------
    s.prog('vln2', *PROGS['vln2_trem'][:2], B(33))
    s.prog('vla', *PROGS['vla_trem'][:2], B(33))
    for n in range(33, 49):
        ch = H[n]
        s.chord('vln2', (CHT[ch][0] + 12, CHT[ch][1] + 12, CHT[ch][2] + 12), 44, B(n), 4.0)
        s.chord('vla', (CHT[ch][1], CHT[ch][2]), 42, B(n), 4.0)
        r1, r2 = CELLO_BASS[n - 32]
        s.note('celli', r1, 50, B(n), 2.0)
        s.note('celli', r2, 48, B(n) + 2, 2.0)
        s.note('bass', ROOT[ch], 46, B(n), 4.0)
        # 钢琴分解(八分音符)
        x = HARP[ch]
        for i in range(6):
            s.note('piano', x[i % 4], 48, B(n) + i * 0.5, 0.35)
    for t, p, d in THEME_D:
        for ft, fp, fd in fig(p, d):
            s.note('flute', fp, 76, B(33) + t + ft, fd)
    for t, p, d in OBOE_ECHO:
        s.note('oboe', p, 68, B(33) + t, d)
    for bn, v in [(33, 58), (37, 64), (41, 66), (45, 68), (47, 62)]:
        dyn('flute', v, bn)
    dyn('vln2', 42, 33); dyn('vla', 40, 33); dyn('oboe', 52, 37)

    # ---------------- 变奏 2(m49-64):g 小调卡农 + 英国管回声 ----------------
